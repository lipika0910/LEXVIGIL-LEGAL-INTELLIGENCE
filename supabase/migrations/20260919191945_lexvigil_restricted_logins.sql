-- Passwordless until secure provisioning; never store credentials in migrations.
CREATE ROLE lexvigil_tenant_login NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 5;
CREATE ROLE lexvigil_auth_login NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 5;
CREATE ROLE lexvigil_worker_login NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 5;
GRANT lexvigil_tenant TO lexvigil_tenant_login WITH INHERIT FALSE, SET TRUE, ADMIN FALSE;
GRANT lexvigil_auth TO lexvigil_auth_login WITH INHERIT FALSE, SET TRUE, ADMIN FALSE;
GRANT lexvigil_worker TO lexvigil_worker_login WITH INHERIT FALSE, SET TRUE, ADMIN FALSE;
GRANT CONNECT ON DATABASE postgres TO lexvigil_tenant_login, lexvigil_auth_login, lexvigil_worker_login;
