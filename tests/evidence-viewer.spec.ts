import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

test('PDF page navigation, exact highlights and deletion fallback', async ({ page }) => {
  const errors:string[]=[];
  page.on('pageerror', e=>errors.push(e.message));
  const bytes=execFileSync('.venv/Scripts/python.exe',['-c', "import pymupdf,sys; d=pymupdf.open(); p=d.new_page(); p.insert_text((60,60),'1.1 Services\\nThe supplier shall provide services.'); p=d.new_page(); p.insert_text((60,60),'2.1 Payment\\nPayment is due within thirty days.'); sys.stdout.buffer.write(d.tobytes())"]);
  await page.goto('/login');
  await page.getByRole('button',{name:'Create an account'}).click();
  await page.getByLabel('Email',{exact:true}).fill(`viewer-${Date.now()}@example.com`);
  await page.getByLabel('Password',{exact:true}).fill('synthetic-password-123');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  await page.getByLabel('Choose contract file').setInputFiles({name:'evidence.pdf',mimeType:'application/pdf',buffer:bytes});
  await page.getByRole('checkbox',{name:/I consent/}).check();
  await page.getByRole('button',{name:'Analyze contract',exact:true}).click();
  await page.getByRole('button',{name:'Open evidence viewer'}).click();
  await expect(page).toHaveTitle(/LexVigil/i);
  await page.getByLabel('Highlight clause').selectOption({index:2});
  await expect(page.getByLabel('Source location')).toHaveValue('1');
  await expect(page.locator('.evidence-text mark')).toHaveText(['2.1 Payment','Payment is due within thirty days.']);
  await page.getByRole('button',{name:'Show PDF page'}).click();
  const image=page.getByRole('img',{name:'Original PDF page 2'});
  await expect(image).toBeVisible();
  await expect.poll(()=>image.evaluate((el:HTMLImageElement)=>el.naturalWidth)).toBeGreaterThan(0);
  await page.getByRole('button',{name:'Previous source'}).click();
  await expect(page.getByRole('img',{name:'Original PDF page 1'})).toBeVisible();
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.locator('.sidebar').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.getByLabel('Highlight clause').selectOption({index:1});
  const viewer=page.getByRole('region',{name:'Evidence viewer'});
  await viewer.screenshot({path:join(process.env.LEXVIGIL_E2E_ARTIFACTS||tmpdir(),'evidence-mobile.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.getByRole('button',{name:'Delete original',exact:true}).click();
  await page.getByRole('button',{name:'Confirm delete original'}).click();
  await expect(viewer).toContainText('PDF image requires an unexpired stored original');
  await expect(page.getByLabel('Extracted source text')).toContainText('supplier');
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  expect(errors).toEqual([]);
});
